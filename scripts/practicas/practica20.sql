/*
Mostrar los detalles de los departamentos en los cuales el salario máximo sea mayor a 10000.
*/

SELECT DEPARTMENT_ID,DEPARTMENT_NAME,MANAGER_ID,LOCATION_ID
FROM DEPARTMENTS
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID
    HAVING DEPARTMENT_ID IS NOT NULL AND MAX(SALARY) > 10000
);



/*
Indicar los tipos de trabajo de los empleados que entraron en la empresa 
entre 2002 y 2003.
*/
SELECT * FROM JOBS
WHERE JOB_ID IN (
    SELECT JOB_ID
    FROM EMPLOYEES
    WHERE HIRE_DATE BETWEEN TO_DATE('2002-01-01', 'YYYY-MM-DD') AND TO_DATE('2003-12-31', 'YYYY-MM-DD')
);



