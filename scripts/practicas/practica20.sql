/*
Mostrar los compañeros que trabajan en el mismo departamento que John Chen 
*/

SELECT EMPLOYEE_ID, FIRST_NAME || ' ' || LAST_NAME AS NAME,DEPARTMENT_ID
FROM EMPLOYEES
WHERE DEPARTMENT_ID IN (

    SELECT DEPARTMENT_ID
    FROM EMPLOYEES
    WHERE FIRST_NAME = 'John' AND LAST_NAME = 'Chen'

);




/*
Qué departamentos tienen su sede en Toronto? 
*/

SELECT DEPARTMENT_ID, DEPARTMENT_NAME FROM DEPARTMENTS
WHERE LOCATION_ID = (
    SELECT LOCATION_ID
    FROM LOCATIONS
    WHERE CITY = 'Toronto'
);




/*
Visualizar los empleados que tengan más de 5 empleados a su cargo. 
*/

SELECT EMPLOYEE_ID,FIRST_NAME || ' ' ||  LAST_NAME AS NAME
FROM EMPLOYEES
WHERE EMPLOYEE_ID IN (
    SELECT E1.EMPLOYEE_ID  FROM EMPLOYEES E1
    JOIN EMPLOYEES E2
    ON E1.EMPLOYEE_ID = E2.MANAGER_ID
    GROUP BY E1.EMPLOYEE_ID
    HAVING COUNT(E2.MANAGER_ID) > 5
);

SELECT E1.EMPLOYEE_ID,COUNT(E2.MANAGER_ID)  FROM EMPLOYEES E1
JOIN EMPLOYEES E2
ON E1.EMPLOYEE_ID = E2.MANAGER_ID
GROUP BY E1.EMPLOYEE_ID
HAVING COUNT(E2.MANAGER_ID) > 5;



/*
¿En qué ciudad trabajar Guy Himuro?
*/

SELECT CITY
FROM LOCATIONS
WHERE LOCATION_ID = (
    SELECT DEP.LOCATION_ID
    FROM EMPLOYEES EM
    JOIN DEPARTMENTS DEP
    ON EM.DEPARTMENT_ID = DEP.DEPARTMENT_ID
    WHERE FIRST_NAME = 'Guy' AND LAST_NAME = 'Himuro'

);

