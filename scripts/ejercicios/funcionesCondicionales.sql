*/
SELECT FIRST_NAME,SALARY,
    CASE WHEN SALARY BETWEEN 0 AND 3000 THEN 'LOW' 
        WHEN SALARY BETWEEN 3001 AND 5000 THEN 'MEDIUM'
        WHEN SALARY > 5001 THEN 'GANAS BIEN'
        ELSE 'NO APLICABLE'
    END
FROM EMPLOYEES;