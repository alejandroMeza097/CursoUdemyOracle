--USO DE CLAUSULA USING. LE INDFICAMOS CUAL COLUMNA USAR
SELECT D.DEPARTMENT_NAME,E.FIRST_NAME,E.SALARY 
FROM EMPLOYEES E JOIN DEPARTMENTS D
    USING (DEPARTMENT_ID)
WHERE SALARY > 5000;

