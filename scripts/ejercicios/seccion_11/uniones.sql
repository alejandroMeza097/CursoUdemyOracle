SELECT E.FIRST_NAME || ' ' || LAST_NAME AS "NAME",E.DEPARTMENT_ID,D.DEPARTMENT_ID, D.DEPARTMENT_NAME,D.LOCATION_ID,LOC.LOCATION_ID,LOC.CITY
FROM EMPLOYEES E
JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN LOCATIONS LOC 
ON D.LOCATION_ID = LOC.LOCATION_ID
AND  E.SALARY > 6000;