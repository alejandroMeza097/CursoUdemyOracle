SELECT DEPARTMENT_ID,DEPARTMENT_NAME,SUM(SALARY) AS SALARIO FROM EMPLOYEES
JOIN DEPARTMENTS
USING (DEPARTMENT_ID)
GROUP BY DEPARTMENT_ID,DEPARTMENT_NAME
HAVING SUM(SALARY) > 20000;


WITH SUMA_SALARIOS AS (

    SELECT DEPARTMENT_ID,SUM(SALARY) AS SALARIO FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID
)
SELECT DEPARTMENT_ID,DEPARTMENT_NAME,SALARIO FROM SUMA_SALARIOS
JOIN DEPARTMENTS
USING (DEPARTMENT_ID)
WHERE SALARIO > 20000;