SELECT EMPLOYEE_ID,FIRST_NAME || ' ' || LAST_NAME AS NAME
FROM EMPLOYEES
WHERE DEPARTMENT_ID IN (

    SELECT DEP.DEPARTMENT_ID
    FROM DEPARTMENTS DEP
    INNER JOIN LOCATIONS LOCS
        ON DEP.LOCATION_ID = LOCS.LOCATION_ID
    WHERE LOCS.CITY = 'Seattle'
);


