SELECT FIRST_NAME || ' ' || LAST_NAME AS "NAME",SALARY
FROM EMPLOYEES
WHERE SALARY > (SELECT AVG(SALARY) FROM EMPLOYEES);


SELECT ROUND(AVG(SALARY)) AS "MEDIA EMPRESA"
FROM EMPLOYEES;

SELECT DEP.DEPARTMENT_NAME,DEP.DEPARTMENT_ID,AVG(EM.SALARY) AS "MEDIA DEPARTAMENTO" FROM EMPLOYEES EM
LEFT JOIN DEPARTMENTS DEP
ON EM.DEPARTMENT_ID = DEP.DEPARTMENT_ID
GROUP BY DEP.DEPARTMENT_ID,DEP.DEPARTMENT_NAME
HAVING AVG(EM.SALARY) > (
    SELECT AVG(SALARY) AS "MEDIA EMPRESA"
    FROM EMPLOYEES
    );


