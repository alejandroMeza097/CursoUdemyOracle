-- ANY ME PERMITE DEVOLVER CUALQUIERA QUE ESTE EN LAS OPCCIONES , DEBE ACOMPAÑARSE DE : > ,< POR EJEMPLO

SELECT FIRST_NAME,LAST_NAME,JOB_ID,SALARY
FROM EMPLOYEES
WHERE SALARY > ANY (

    SELECT SALARY
    FROM EMPLOYEES
    WHERE JOB_ID = 'IT_PROG'
)
AND JOB_ID != 'IT_PROG';


